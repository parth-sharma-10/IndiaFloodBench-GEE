"""Write data_quality_report.md and FINAL_AUDIT.md from the packaged files (re-reads everything)."""
import glob
import json
import os
from pathlib import Path

import numpy as np
import pandas as pd
import rasterio


def pct(x):
    return f"{100 * x:.1f}%"


def md_table(df):
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join(str(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join(lines)


def coverage(df):
    g = df.groupby("event_id")
    return pd.DataFrame({
        "S1 before": g["VV_before"].apply(lambda s: pct(s.notna().mean())),
        "S1 after": g["VV_after"].apply(lambda s: pct(s.notna().mean())),
        "S2 before": g["NDVI_before"].apply(lambda s: pct(s.notna().mean())),
        "S2 after": g["NDVI_after"].apply(lambda s: pct(s.notna().mean())),
        "rainfall": g["rainfall_1d"].apply(lambda s: pct(s.notna().mean())),
        "DEM": g["elevation"].apply(lambda s: pct(s.notna().mean())),
        "landcover": g["landcover_class"].apply(lambda s: pct(s.notna().mean())),
    }).reset_index()


def hand_agreement(root, key="gfm_vs_hand"):
    tp = fp = fn = tn = 0
    n = 0
    for p in glob.glob(str(root / "data/raster/*/*/patch.json")):
        a = json.loads(Path(p).read_text()).get(key)
        if a:
            n += 1
            tp, fp, fn, tn = tp + a["tp"], fp + a["fp"], fn + a["fn"], tn + a["tn"]
    if not n:
        return None
    return {"patches": n, "pixels": tp + fp + fn + tn, "tp": tp, "fp": fp, "fn": fn, "tn": tn,
            "precision": tp / max(1, tp + fp), "recall": tp / max(1, tp + fn), "iou": tp / max(1, tp + fp + fn)}


def raster_audit(root):
    files = sorted(glob.glob(str(root / "data/raster/*/*/*.tif")))
    bad, crs, shapes = [], set(), set()
    for f in files:
        try:
            with rasterio.open(f) as ds:
                ds.read(1)
                crs.add(str(ds.crs))
                shapes.add((ds.width, ds.height, ds.res))
        except Exception as e:  # noqa: BLE001 - reported, not hidden
            bad.append(f"{f}: {e}")
    patches = len(glob.glob(str(root / "data/raster/*/*/patch.json")))
    return {"files": len(files), "unreadable": bad, "crs": sorted(crs), "shapes": sorted(shapes), "patches": patches}


def du(path):
    total = 0
    for dp, _, fs in os.walk(path):
        total += sum(os.path.getsize(os.path.join(dp, f)) for f in fs)
    return total


def write_reports(root):
    df = pd.read_parquet(root / "data/tabular/indiafloodbench.parquet")
    csv_rows = sum(1 for _ in open(root / "data/tabular/indiafloodbench.csv")) - 1
    ev = pd.read_csv(root / "events.csv")
    val = json.loads((root / "reports/validation.json").read_text())
    ds = val.get("_dataset", {})
    agree = hand_agreement(root)
    ra = raster_audit(root)
    cov = coverage(df)
    built = ev[ev.status == "complete"]
    not_built = ev[ev.status != "complete"]

    per_event = built[["event_id", "slug", "state", "event_type", "label_date", "patches", "total_samples",
                       "positive_samples", "negative_samples", "positive_percentage",
                       "aoi_flood_fraction_of_labelled_px"]].copy()
    per_event["aoi_flood_fraction_of_labelled_px"] = per_event["aoi_flood_fraction_of_labelled_px"].map(
        lambda v: "" if pd.isna(v) else pct(v))
    vrows = [{"event_id": k, "passed": v["passed"], "errors": len(v["errors"]),
              "warnings": "; ".join(v["warnings"]) or "-"} for k, v in val.items() if k != "_dataset"]
    miss = pd.Series(ds.get("missing_fraction", {})).sort_values(ascending=False)
    miss_tbl = pd.DataFrame({"column": miss.index, "missing": [pct(v) for v in miss.values]})

    lines = [
        "# IndiaFloodBench - data quality report", "",
        "Generated by `scripts/generate_report.py report` from the packaged files and `reports/validation.json`.", "",
        "## Event balance", "", md_table(per_event), "",
        "`positive_percentage` is the share of flood samples after **stratified** sampling (<=150 flood + "
        "<=150 non-flood lattice pixels per patch). The natural flood share of labelled pixels in the AOI is "
        "`aoi_flood_fraction_of_labelled_px`; use `inclusion_prob` to reweight to it.", "",
        "## Events not in the dataset", "",
        md_table(not_built[["event_id", "slug", "status", "failure_reason"]]) if len(not_built) else "None.", "",
        "## Sensor coverage (share of samples with a value)", "", md_table(cov), "",
        "Sentinel-2 gaps are clouds: the after-window is +-days around a monsoon flood, so most flood-day "
        "optical pixels are cloudy. These are left as NaN, never filled.", "",
        "## Missing values (whole dataset, columns with any missing)", "",
        md_table(miss_tbl) if len(miss_tbl) else "None.", "",
        "## Duplicates", "",
        f"- duplicate `sample_id`: {ds.get('duplicate_sample_id')}",
        f"- duplicate full rows: {ds.get('duplicate_rows_all_columns')}",
        f"- duplicate (event, lat, lon): {ds.get('duplicate_event_lat_lon')}",
        f"- same (lat, lon) in different events: {ds.get('cross_event_same_lat_lon')} "
        "(expected only where AOIs of different years overlap; they are different observations)", "",
        "## Geographic validation", "",
        "- all samples inside their event bbox (+-0.1 deg) and inside India's lat/lon envelope: "
        + ("yes" if all(v["passed"] or not any("bbox" in e for e in v["errors"]) for k, v in val.items() if k != "_dataset") else "NO"),
        f"- samples whose own state (geoBoundaries ADM1 at the pixel, column `state`) differs from the event's "
        f"catalogue state (`event_state`): {ds.get('pixel_state_differs_from_event_state'):,}. These are AOIs that "
        "cross state borders, not errors. Per event:",
        "", md_table(pd.DataFrame([{"event -> pixel state": k, "samples": v}
                                   for k, v in ds.get("pixel_state_by_event", {}).items()])), "",
        f"- samples with no state (more than ~5 km outside every ADM1 polygon): {ds.get('samples_without_state')}; "
        f"of these labelled flood: {ds.get('flood_samples_without_state')} (should be ~0; open sea labelled flood "
        "shows up here)", "",
        "## Temporal, raster and label validation (per event)", "", md_table(pd.DataFrame(vrows)), "",
        "Checks: S1 before dates inside the pre-event window and before `event_start`; S1 after date == "
        "label date; all 9 GeoTIFFs per patch share CRS/transform/size, are 20 m and set nodata; flood and "
        "non-flood samples both present; label values only 0/1 in the table.", "",
        "## Label quality: GFM vs. hand labels (IFB-001, Assam 2016-08-12)", "",
    ]
    agree_f = hand_agreement(root, "gfm_flood_extent_vs_hand")
    if agree:
        lines += [f"On {agree['patches']} Sen1Floods11 chips, the IndiaFloodBench GFM-based label (GFM observed "
                  f"water minus JRC permanent water) of the same Sentinel-1 pass, against the hand label "
                  f"({agree['pixels']:,} pixels labelled by both): precision {agree['precision']:.3f}, "
                  f"recall {agree['recall']:.3f}, IoU {agree['iou']:.3f} "
                  f"(TP {agree['tp']:,} / FP {agree['fp']:,} / FN {agree['fn']:,} / TN {agree['tn']:,}).", ""]
    if agree_f:
        lines += [f"GFM's own flood extent (minus monthly reference water) on the same chips: precision "
                  f"{agree_f['precision']:.3f}, recall {agree_f['recall']:.3f}, IoU {agree_f['iou']:.3f}. "
                  "This is why it is not used as the label (dataset_card.md).", ""]
    if not agree and not agree_f:
        lines += ["No GFM scene overlapped the hand-labelled chips; agreement not computed.", ""]
    lines += ["This is the only direct check of GFM-derived labels in the dataset, on one event in one "
              "region; label quality on the other events is unmeasured.", ""]
    (root / "data_quality_report.md").write_text("\n".join(lines))

    states = sorted(df["state"].dropna().unique())
    fl, nf = int((df.flood_label == 1).sum()), int((df.flood_label == 0).sum())
    audit = [
        "# FINAL AUDIT", "",
        "Every number below was computed by re-reading the output files "
        "(`scripts/generate_report.py report`).", "",
        f"- **Number of flood events:** {len(built)} built ({len(ev)} configured; "
        f"{len(not_built)} not built: {', '.join(not_built.slug) or '-'})",
        f"- **States covered:** {', '.join(states)} ({len(states)} with samples; event catalogue states: "
        f"{', '.join(sorted(built['state'].unique()))})",
        f"- **Date range:** {built.event_start.min()} to {built.event_end.max()} (labels {built.label_date.min()} to {built.label_date.max()})",
        f"- **Total samples:** {len(df):,} (Parquet rows) / {csv_rows:,} (CSV rows)",
        f"- **Flood samples:** {fl:,} ({pct(fl / len(df))})",
        f"- **Non-flood samples:** {nf:,} ({pct(nf / len(df))})",
        f"- **Number of raster patches:** {ra['patches']} (256x256 px at 20 m), {ra['files']} GeoTIFFs, "
        f"{len(ra['unreadable'])} unreadable; CRS used: {', '.join(ra['crs'])}",
        f"- **Total storage:** data/ {du(root / 'data') / 1e6:.0f} MB (raster {du(root / 'data/raster') / 1e6:.0f} MB, "
        f"tabular {du(root / 'data/tabular') / 1e6:.0f} MB, external inputs {du(root / 'data/external') / 1e6:.0f} MB)",
        f"- **Sentinel-1 coverage:** before {pct(df.VV_before.notna().mean())}, after {pct(df.VV_after.notna().mean())} of samples",
        f"- **Sentinel-2 coverage:** before {pct(df.NDVI_before.notna().mean())}, after {pct(df.NDVI_after.notna().mean())} of samples",
        f"- **Rainfall coverage:** {pct(df.rainfall_14d.notna().mean())} (CHIRPS v2.0 daily, 0.05 deg)",
        f"- **DEM coverage:** {pct(df.elevation.notna().mean())} (Copernicus GLO-30)",
        f"- **Label sources:** " + "; ".join(f"{k}: {v:,} samples" for k, v in df.label_source.value_counts().items()),
        "", "## Missing data", "",
        "; ".join(f"{r.column} {r.missing}" for r in miss_tbl.itertuples()) or "none", "",
        "## Duplicate data", "",
        f"sample_id duplicates {ds.get('duplicate_sample_id')}, full-row duplicates {ds.get('duplicate_rows_all_columns')}, "
        f"(event, lat, lon) duplicates {ds.get('duplicate_event_lat_lon')}.", "",
        "## Known limitations", "",
        "- Features come from Google Earth Engine; Earth Engine's Sentinel-1 (`COPERNICUS/S1_GRD`) is sigma0, not "
        "terrain-flattened gamma0, so radar values differ from v1.0 (built from Planetary Computer RTC) by a few dB.",
        "- Labels do not come from Earth Engine: GFM is read from EODC and Sen1Floods11 hand labels from its bucket; "
        "neither is in the Earth Engine catalogue.",
        "- 9 of 10 configured events use GFM labels, which are automated and derived from the SAME Sentinel-1 "
        "acquisition as `VV_after`/`VH_after`. Models using after-SAR features against GFM labels partly learn "
        "the GFM algorithm. See dataset_card.md.",
        "- Urban flooding is essentially unlabelled: GFM excludes built-up pixels (Hyderabad 2020 and Mumbai 2024 "
        "probes had ~0 GFM flood pixels and were dropped). Vadodara/Vijayawada labels are mostly peri-urban water.",
        "- GFM-based labels are conservative: on IFB-001 they recover 35% of hand-labelled flood (precision 0.76).",
        "- Label = observed non-permanent water; in July paddy and urban fringes part of it is seasonal water, not flood.",
        "- Sentinel-2 after-imagery is mostly cloud-covered for monsoon events.",
        "- Land cover is ESA WorldCover 2021 (static); Dynamic World probabilities are not included.", "",
        "## Files generated", "",
    ]
    for pat in ["README.md", "dataset_card.md", "schema.md", "data_quality_report.md", "events.csv", "LICENSE",
                "configs/*.json", "src/ifb/*.py", "scripts/*.py", "state/*.json", "data/metadata/*.json",
                "data/tabular/*.parquet", "data/tabular/*.csv", "data/tabular/events/*.parquet", "reports/*.json"]:
        fs = sorted(glob.glob(str(root / pat)))
        audit.append(f"- `{pat}`: {len(fs)} file(s)" + (f" - {', '.join(Path(f).name for f in fs[:12])}"
                                                     + (" ..." if len(fs) > 12 else "") if fs else " - **MISSING**"))
    audit.append(f"- `data/raster/<event>/<patch>/*.tif`: {ra['files']} files in {ra['patches']} patch folders")
    (root / "FINAL_AUDIT.md").write_text("\n".join(audit) + "\n")
    print("\n".join(audit))
